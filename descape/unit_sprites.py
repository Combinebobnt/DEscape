"""Resolves a unit to its real in-game sprite: unit_const -> .sld frame -> a
tinted, scaled RGBA array the Stepped compositor can paste.

Leaf module. numpy and stdlib only -- no Qt, no genieutils, and nothing here
reaches into descape/render.py.

**No game assets are shipped.** Pixels are read from the user's own configured
AoE2:DE install at runtime, the same posture asset_source.py takes for terrain
textures. descape/unit_graphic_map.json (committed, generated by
tools/gen_unit_graphic_map.py) is a factual data table extracted from the
game's unit and graphic tables, not asset content.

Everything below falls back to None rather than raising. A caller that gets
None draws today's coloured mark, so an absent install, an absent file, an
unreadable file and an undecodable frame are all exactly as safe as "no install
configured" already is.

## How a unit becomes a frame

A graphic's frames are stored **angle-major**: `frames[angle * frame_count]` is
that angle's first (standing) pose, which is the only one a scenario editor
needs -- there is no animation loop here. `angle_count` is the number of angles
actually stored; `mirroring_mode` does NOT halve it, despite the usual AoE2
convention (measured over 400 graphics: total_frames - angle_count*frame_count
is 0 or 1, never half, and a graphic's stored frames are pixel-distinct rather
than mirrored duplicates). Animated graphics carry one extra frame at the END,
so no index offset is needed.

## How player colour is applied

The MAIN layer renders the player-coloured region in near-grey, and the
PLAYERCOLOR layer is a per-pixel COVERAGE mask (its interior sits at 255, its
boundary ramps -- it is antialiasing, not a shade index). The tint is a plain
multiply by one RGB per player:

    out = lerp(main, main * team_rgb, coverage)

TEAM_COLORS below are the game's own, read from its
resources/_common/palettes/spritecolors.json. The 256-entry playercolor_*.pal
files are the legacy SLP path and must NOT be used here: their entries 128..255
are all black, while MAIN's luminance under the mask reaches 247, so indexing
them by luminance paints most sprites black.
"""

