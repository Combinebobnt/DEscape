def variant_index(rotation: float, angle_count: int) -> int:
    """Which stored frame a rotation selects when the graphic's frames are
    shape variants rather than facings -- walls, confirmed by direct frame
    decode (see below).

    b_west_wall_stone_x1's five frames were decoded and inspected: 0 and 1 are
    wall runs along each screen diagonal, 2 is a tall tower, 3 a flatter run,
    4 a narrow column. A wall cannot be *rotated* into a tower, so the field
    selects a shape. Correlating rotation against wall connection topology
    across the example corpus confirmed integers 0..4 map 1:1 onto them.

    Real files use TWO conventions for the same graphic, and the corpus scan
    found a rare THIRD, so:

    - `rotation` within 1e-6 of an integer in [0, angle_count) is the variant
      index written directly -- use it as-is.
    - Otherwise treat it as that same index re-encoded as
      `index * 2*pi / angle_count` radians (the other convention real files
      ship) and solve for it with the ordinary angle formula.
    - That also absorbs the rare hand-rotated outlier (measured: one 5.969026
      among 1361 Palisade Wall placements, one each of 3.298672 and 4.084071
      among 4437 Stone Wall placements). There is no "correct" discrete frame
      for a freely-rotated wall piece, since the premise is that the frames are
      a few discrete shapes rather than a continuum; this just picks one
      deterministically, as angle_index() already does for off-grid values.

    The closeness test is against the RAW rotation, not against the angle
    formula's rounded output, and that distinction is load-bearing: at
    angle_count 5, index 2's radian encoding is 2.513274, which is CLOSER to 3
    than to 2 (0.4867 vs 0.5133), so "round the raw value to nearest int" would
    misfile it as 3. Testing raw closeness to an exact integer instead routes
    2.513274 to the angle branch, which resolves it to exactly 2, because
    0.4867 is nowhere near the 1e-6 window a literally-written index lands in.

    NEVER applies ANGLE_ZERO_OFFSET_DEG, by construction rather than because it
    happens to be skipped at angle_count 5. That offset corrects a physical
    camera-relative facing; a variant-index graphic has no facing to correct,
    so applying it would be wrong even for a future wall-like graphic whose
    angle_count did happen to be a multiple of 8.
    """
    if angle_count <= 1:
        return 0
    nearest = round(rotation)
    if abs(rotation - nearest) < 1e-6 and 0 <= nearest < angle_count:
        return int(nearest)
    steps = rotation / (2 * math.pi) * angle_count
    # floor(x + 0.5) rather than round(), for the same banker's-rounding reason
    # angle_index() spells out.
    return math.floor(steps + 0.5) % angle_count


def _graphics_dir() -> Path | None:
    root = asset_source.get_install_path()
    return None if root is None else root / GRAPHICS_SUBPATH


def _native_frame(file_name: str, frame_index: int):
    """(main, playercolor, hotspot_x, hotspot_y) at native resolution, or None.

    Swallows every failure into None on purpose -- see the module docstring.
    decode_frame() is the half that RAISES (SLDError, on a command stream that
    overruns its own block grid); load_sld() is the half that never does.
    """
    key = (file_name, frame_index)
    hit = _native_cache.get_or_none(key)
    if hit is not None:
        return hit

    directory = _graphics_dir()
    if directory is None:
        return None
    sld = load_sld(directory / f"{file_name}.sld")
    if sld is None:
        return None
    # The .dat's angle_count * frame_count overruns the real frame count on a
    # small minority of graphics, so trust the file, not the arithmetic.
    if not (0 <= frame_index < sld.frame_count):
        return None
    try:
        frame = sld.decode_frame(frame_index)
    except SLDError as exc:
        debug_log.log(f"sprite: {file_name} frame {frame_index} failed to decode: {exc}")
        return None
    if frame.main is None:
        return None
    # DAMAGE is deliberately not composited: it is a packed mask that BC1
    # happens to carry, not colour. SHADOW and OUTLINE are likewise skipped.
    value = _cropped_to_ink(frame.main, frame.playercolor, frame.hotspot_x, frame.hotspot_y)
    if value is None:
        return None
    _native_cache.put(key, value)
    return value


def _cropped_to_ink(main: np.ndarray, playercolor: np.ndarray | None, hx: int, hy: int):
    """(main, playercolor, hotspot_x, hotspot_y) trimmed to MAIN's opaque bbox.

    **A frame's canvas is mostly empty, and keeping the margin is expensive
    twice over.** Measured across 200 real graphics, the opaque bbox is a
    median 6% and a mean 10% of the canvas area -- a villager's ink is 15x39
    inside a 200x200 canvas. Uncropped, that margin is cached as RGBA bytes and
    then alpha-blended, pixel by pixel, on every composite that touches the
    sprite.

    Cropping moves the hotspot, so it is returned rebased rather than left for
    the caller to correct -- a sprite whose hotspot still refers to the
    uncropped canvas lands a whole margin's width off its tile.

    None if the frame has no opaque pixel at all: there is nothing to draw, and
    a zero-size array would only fail further downstream.
    """
    opaque = main[..., 3] > 0
    if not opaque.any():
        return None
    rows = np.flatnonzero(opaque.any(axis=1))
    cols = np.flatnonzero(opaque.any(axis=0))
    y0, y1 = int(rows[0]), int(rows[-1]) + 1
    x0, x1 = int(cols[0]), int(cols[-1]) + 1
    # np.ascontiguousarray so the cache holds the crop's own bytes rather than
    # a view keeping the whole decoded canvas alive.
    cropped_main = np.ascontiguousarray(main[y0:y1, x0:x1])
    cropped_pc = None if playercolor is None else np.ascontiguousarray(playercolor[y0:y1, x0:x1])
    return cropped_main, cropped_pc, hx - x0, hy - y0


def _tinted(main: np.ndarray, playercolor: np.ndarray | None, team: tuple[int, int, int]):
    """main * team, applied through playercolor's coverage. See the module
    docstring for why this is a multiply and not a palette lookup."""
    if playercolor is None or team == (255, 255, 255):
        return main
    rgb = main[..., :3].astype(np.float32)
    cov = np.where(playercolor[..., 3] > 0, playercolor[..., 0], 0).astype(np.float32) / 255.0
    cov = cov[..., None]
    t = np.array(team, dtype=np.float32) / 255.0
    out = main.copy()
    out[..., :3] = np.clip(rgb * (1 - cov) + rgb * t * cov, 0, 255).astype(np.uint8)
    return out


def _resize_rgba(rgba: np.ndarray, width: int, height: int) -> np.ndarray:
    """Nearest-neighbour box resample. Deliberately not Pillow: this module
    stays Qt-free and image-library-free like the rest of the render path, and
    a sprite shrunk to tile scale is being decimated, not enlarged."""
    src_h, src_w = rgba.shape[:2]
    ys = np.minimum((np.arange(height) * src_h) // height, src_h - 1)
    xs = np.minimum((np.arange(width) * src_w) // width, src_w - 1)
    return rgba[ys[:, None], xs[None, :]]


def sprite_scale(half_w: int) -> float:
    """Native sprite pixels -> canvas pixels, for a projection whose tile
    diamond is 2*half_w wide. One expression, so the mip ladder and any
    tile_px change follow it for free."""
    return 2 * half_w / NATIVE_TILE_W


def _draw_for_entry(
    unit_const: int, entry: dict, rotation: float, team_index: int, half_w: int
) -> SpriteDraw | None:
    """The tinted, scaled sprite `entry` (one graphic_map() record) resolves
    to, or None on any of the failure paths sprite_for()'s docstring lists.

    `unit_const` is a parameter, not read off `entry`, so a piece can pass its
    OWN resolving unit_id here (see sprite_pieces_for()) while `entry` still
    carries that piece's own file_name/angle_count/frame_count -- a piece's
    frame dispatch is a property of its own graphic, never of whichever unit
    happens to be standing on the map.

    `team_index` is TEAM_COLORS' own index (0 = GAIA, 1..8 = that ColorId's
    tint), not a player_id -- a scenario's stored color override can put any
    player on any tint, so the caller resolves player_id -> team_index
    itself (see scenario_io.LoadedScenario.team_indices) before calling
    here."""
    angle_count = max(1, int(entry["angle_count"]))
    frame_count = max(1, int(entry["frame_count"]))
    frame = (
        variant_index(rotation, angle_count)
        if _rotation_is_variant(unit_const)
        else angle_index(rotation, angle_count)
    )
    index = frame * frame_count

    scale = sprite_scale(half_w)
    team = TEAM_COLORS[team_index % len(TEAM_COLORS)]
    # Keyed on team_index, not player_id: two scenarios' player 1 can resolve
    # to different stored colors, and this cache is a process-global LRU that
    # would otherwise serve one scenario's tinted sprite to the other's.
    key = (entry["file_name"], index, team_index % len(TEAM_COLORS), half_w)
    hit = _scaled_cache.get_or_none(key)
    if hit is not None:
        return None if hit is _MISS else hit

    native = _native_frame(entry["file_name"], index)
    if native is None:
        _scaled_cache.put(key, _MISS)  # see _MISS -- re-deriving this is expensive
        return None
    main, playercolor, hx, hy = native

    width = max(1, round(main.shape[1] * scale))
    height = max(1, round(main.shape[0] * scale))
    draw = SpriteDraw(
        rgba=_resize_rgba(_tinted(main, playercolor, team), width, height),
        hotspot_x=round(hx * scale),
        hotspot_y=round(hy * scale),
    )
    _scaled_cache.put(key, draw)
    return draw


def sprite_for(
    unit_const: int, rotation: float, team_index: int, half_w: int
) -> SpriteDraw | None:
    """This unit's tinted, scaled sprite, or None to fall back to a mark.

    None is returned, never an exception, for every one of: a unit_const with
    no graphic; no install configured; the .sld missing on this install; the
    file unreadable (bad magic, zero bytes, or a layout variant that is neither
    14 nor 16); a frame index past the file's real end; and a frame whose
    decode raises.

    For a composite building (unit_graphic_map.json's optional "pieces" key),
    this draws only the entry's OWN graphic -- unchanged behavior for every
    existing caller. sprite_pieces_for() is the composite-aware sibling.
    """
    entry = graphic_map().get(unit_const)
    if entry is None:
        return None
    return _draw_for_entry(unit_const, entry, rotation, team_index, half_w)


def sprite_pieces_for(
    unit_const: int, rotation: float, team_index: int, half_w: int
) -> list[SpritePiece]:
    """The full ordered composite for unit_const: ready-to-paste pieces, each
    with its own (dx, dy) screen offset from the unit's own anchor. Empty on
    total failure (no entry, or the parent piece fails to resolve) so the
    caller falls back to today's coloured mark, unchanged. A unit_const with
    no "pieces" key resolves to a single piece at (0, 0) -- callers do not
    need two code paths for a composite vs. a plain unit.

    A non-parent piece that fails to resolve is skipped rather than failing
    the whole composite -- strictly better than today, never worse. Each
    piece resolves through its OWN resolving unit_id (unit_graphic_map.json's
    per-piece "unit_id" -- this const itself for the parent's own piece, an
    annex's unit_id otherwise), never unit_const for every piece: a piece's
    frame dispatch is a property of its own graphic (see _draw_for_entry),
    and pieces can carry a different angle_count/rotation-dispatch than their
    parent even though every currently-composited piece is angle-index-based
    like its parent today.
    """
    entry = graphic_map().get(unit_const)
    if entry is None:
        return []
    pieces_data = entry.get("pieces")
    if not pieces_data:
        draw = _draw_for_entry(unit_const, entry, rotation, team_index, half_w)
        return [] if draw is None else [SpritePiece(draw=draw, dx=0, dy=0)]

    scale = sprite_scale(half_w)
    result: list[SpritePiece] = []
    for piece in pieces_data:
        draw = _draw_for_entry(piece["unit_id"], piece, rotation, team_index, half_w)
        if draw is None:
            # The parent's own piece (unit_id == unit_const) is identified by
            # identity, not list position -- depth order can (and for a town
            # centre's back piece, does) place it anywhere but index 0.
            if piece["unit_id"] == unit_const:
                return []
            continue
        result.append(SpritePiece(
            draw=draw,
            dx=round(piece["dx"] * scale),
            dy=round(piece["dy"] * scale),
        ))
    return result


def anchor_tile_coords(
    tile_x0: int, tile_y0: int, span_x: int, span_y: int
) -> tuple[float, float]:
    """The continuous tile coordinate a sprite's hotspot sits on: the
    FOOTPRINT'S CENTRE, not the anchor tile's diamond centre (those differ by
    half a tile on an even span) and not the sprite's top-left corner, which is
    what a naive blit does and what offsets every sprite from its tile.

    Verified against the game's own art: a 3x3 Barracks' stone base lands on
    exactly its own footprint diamond under this rule, with only the palisade
    overhanging -- which is what it does in game."""
    return tile_x0 + span_x / 2, tile_y0 + span_y / 2


def sprite_anchor_tile(
    tile_x0: int, tile_x1: int, tile_y0: int, tile_y1: int
) -> tuple[int, int]:
    """Which footprint tile's moment in the depth walk paints the sprite.

    A sprite is ONE image over the whole footprint, so it must paint once --
    unlike the diamond path, where _units_by_tile buckets a building into every
    footprint tile and each diamond lands at its own tile's depth position.

    The tile chosen is the one that comes LAST in depth_order: maximal
    d = y - x, tie-broken on ascending x, the same key composite_rect_iso's own
    np.lexsort((xs, ys - xs)) uses. Reusing that key rather than an ad-hoc
    max(x + y) matters because a divergence here is a paint-order mismatch that
    tests/test_unit_pick.py's ID-plane oracle cannot catch -- picking still goes
    through the diamond path and is unaffected by sprites.

    Painting last within the footprint means every footprint tile's terrain is
    already down, while terrain nearer than the building still paints over the
    sprite, exactly as it does for diamonds today.
    """
    best = None
    for ty in range(tile_y0, tile_y1):
        for tx in range(tile_x0, tile_x1):
            key = (ty - tx, tx)
            if best is None or key > best[0]:
                best = (key, (tx, ty))
    return best[1]
