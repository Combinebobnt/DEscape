# DE's own iso tile diamond width for x1 assets. Measured against the spans the
# game's unit table reports, not read off a wiki: a building sprite's ink
# extends symmetrically about its hotspot by span * 96 / 2 in x and reaches
# span * 96 / 4 below it in y (House 2x2 -84..+79 vs +-96; Barracks 3x3
# -148..+140 vs +-144; Wonder 5x5 -249..+248 vs +-240).
NATIVE_TILE_W = 96

# How far the farthest sprite's pixels reach past its own hotspot, per side, in
# the same native px NATIVE_TILE_W is in -- so a canvas-pixel padding is
# reach * sprite_scale(half_w). descape/render.py's _sprite_reach_px is the only
# consumer: it turns these into the per-side widening an edit's dirty bbox needs
# so a sprite standing on a dirty tile cannot escape it and leave a stale
# fragment behind.
#
# Measured by tools/scan_sprite_reach.py over every .sld descape/
# unit_graphic_map.json references, from each frame's MAIN-layer header box
# (which bounds the ink bbox _cropped_to_ink produces). The worst file is named
# per direction so a re-scan after a game patch either reproduces the number or
# says which graphic grew. UP dominates by a wide margin -- wonders and
# cathedrals out-reach every horizontal case by 50%.
MAX_SPRITE_REACH_LEFT = 404   # b_scen_cathedral_rubble_x1
MAX_SPRITE_REACH_RIGHT = 424  # b_scen_cathedral_rubble_x1
MAX_SPRITE_REACH_UP = 650     # b_west_wonder_britons_x1
MAX_SPRITE_REACH_DOWN = 200   # b_scen_colosseum_x1

# How far the stored angle set is rotated from the scenario's own `rotation`
# field, in degrees, and which way the index walks as rotation increases.
#
# **The offset is ANGULAR, not an index offset, and that distinction is the
# whole reason this constant is in degrees.** Index 0 is a fixed compass
# direction for every graphic regardless of how many angles it stores, so a
# correction of "45 degrees" is 1 step for an angle_count of 8 but 2 for 16 and
# 4 for 32. angle_count is nowhere near uniform -- measured over the 2,439
# graphics unit_graphic_map.json references, 16 dominates at 1,163 and 8 is
# rare at 76, with everything from 2 to 72 present. An index-space constant
# (which this was until 2026-08-24) therefore cannot express a fixed angular
# correction at all: it would rotate most units by 22.5 degrees while rotating
# a handful by 45.
#
# The magnitude comes from a live-window observation: units rendered 45 degrees
# to the RIGHT of where the real editor puts them, uniformly. Uniformly is the
# load-bearing word -- a wrong ANGLE_DIRECTION would MIRROR the facing about an
# axis, so the error would vary with rotation instead of being constant. That
# it is constant is what says the direction is already right and only the zero
# point was off.
#
# **The sign is -45, confirmed against the running game, and it is worth
# knowing WHY it is not +45.** Correcting a "units face 45 degrees too far
# right" error means adding 45 degrees if the game's `rotation` grows
# counter-clockwise and subtracting it if clockwise. Nothing in the .sld, the
# .dat or openage states which, so +45 was tried first on the reasoning that a
# radians field usually follows the maths convention. That put units 90 degrees
# out -- the signature of a sign error, being exactly twice the offset -- so
# **AoE2's rotation field grows CLOCKWISE on screen.** Recorded here because it
# cost a round trip to a human with the game open, and nothing else in this
# codebase pins it.
ANGLE_ZERO_OFFSET_DEG = -45.0
ANGLE_DIRECTION = 1

# resources/_common/palettes/spritecolors.json's TeamColors block, as RGB.
# Index is the scenario's own player id: 0 is GAIA, 1..8 the real players.
# GAIA's (255, 255, 255) multiplies to identity, so a GAIA unit needs no
# special case anywhere.
TEAM_COLORS = (
    (255, 255, 255),  # GAIA
    (0, 0, 255),
    (255, 0, 0),
    (0, 169, 27),
    (214, 214, 27),
    (123, 239, 240),
    (138, 19, 247),
    (102, 102, 102),
    (255, 146, 5),
)

# Sized by tools/bench_unit_sprites.py (P3-g4), not guessed. Both matter
# because sld_decoder holds no cache of its own and a delta chain can be 313
# links deep, so one wanted frame can pay for hundreds of predecessor decodes.
#
# **The failure mode these avoid is a cache that silently does nothing.** At
# the first-pass 256, the worst real file (old-allies-final-v2, 652 distinct
# (file, frame) pairs before the per-player and per-mip-level multiplier) ran
# a WARM layer rebuild in 4562ms against a 4768ms cold one -- every entry was
# evicted before it could be reused, so the cache cost memory and bought
# nothing. It is not enough for a capacity to be "big"; it has to exceed a
# real file's distinct-key count, or it is worse than no cache at all.
#
# Entry counts rather than a byte budget, because cropping to the ink bbox
# made entries small and predictable: measured across the three biggest
# example files, a scaled entry averages ~19KB and a native one ~200KB. So
# these caps are roughly 40MB scaled and 50MB native at worst, and typically a
# small fraction of that.
NATIVE_CACHE_SIZE = 256
SCALED_CACHE_SIZE = 2048


@dataclass(frozen=True)
class SpriteDraw:
    """One unit's sprite, ready to paste.

    rgba is (h, w, 4) uint8 already tinted for its owner and already scaled for
    the caller's tile_px. hotspot_x/y are in that same scaled pixel space, and
    are the pixel that sits on the ground anchor -- see anchor_screen_pos().
    """

    rgba: np.ndarray
    hotspot_x: int
    hotspot_y: int


@dataclass(frozen=True)
class SpritePiece:
    """One piece of a composite building's sprite (a town centre's back/main/
    center/front, a pasture's corner posts), ready to paste at an offset from
    the unit's own anchor. dx/dy are in the same scaled canvas-pixel space as
    SpriteDraw's hotspot -- see sprite_pieces_for()."""

    draw: SpriteDraw
    dx: int
    dy: int


class _LRU(OrderedDict):
    """Smallest thing that is actually an LRU. functools.lru_cache can't be
    used for the scaled cache: its capacity has to stay adjustable from
    P3-g4's bench without redecorating a module-level function."""

    def __init__(self, capacity: int):
        super().__init__()
        self.capacity = capacity

    def get_or_none(self, key):
        if key in self:
            self.move_to_end(key)
            return self[key]
        return None

    def put(self, key, value):
        self[key] = value
        self.move_to_end(key)
        while len(self) > self.capacity:
            self.popitem(last=False)


_native_cache = _LRU(NATIVE_CACHE_SIZE)
_scaled_cache = _LRU(SCALED_CACHE_SIZE)

# Cached in place of a sprite when a key resolves to nothing.
#
# **Caching the negative result is not an optimization, it is the difference
# between a working cache and a broken one.** A unit that resolves nowhere --
# no file on this install, a frame index past the file's end -- costs a full
# SLDFile walk to discover that, every single time.
# Measured on the 32,272-unit corpus outlier before this existed: a WARM layer
# rebuild spent 1.59s of its 1.74s inside SLDFile.__init__, re-walking files
# 641 times to re-derive answers it already had. Only ~1% of that file's units
# are unresolvable; they were most of its cost.
_MISS = object()


def clear_caches() -> None:
    """Drops both LRUs. For tests, and for a settings change that repoints the
    install path -- a cached array outlives the file it came from otherwise."""
    _native_cache.clear()
    _scaled_cache.clear()


@lru_cache(maxsize=1)
def graphic_map() -> dict[int, dict]:
    """unit_const -> {graphic_id, file_name, angle_count, mirroring_mode,
    frame_count}, from the committed table."""
    data = json.loads(GRAPHIC_MAP_PATH.read_text())["graphics"]
    return {int(k): v for k, v in data.items()}


def angle_index(rotation: float, angle_count: int) -> int:
    """Which stored angle a rotation (radians) selects.

    Real rotations are NOT quantized -- across the example corpus 20,122
    non-GAIA units carry 34 distinct values, mixing exact 16-grid points with
    hand-typed round numbers, 40% of them 0.0, and ~4% outside [0, 2*pi)
    entirely (7.0 appears 574 times). So this rounds and wraps rather than
    looking anything up.

    GAIA is the caller's problem, not this function's: a GAIA object's
    `rotation` is a doodad graphic-variant index, not an angle (see AGENTS.md's
    hard rule), so it must never be passed here.
    """
    if angle_count <= 1:
        return 0
    steps = rotation / (2 * math.pi) * angle_count
    # ANGLE_ZERO_OFFSET_DEG is converted into THIS graphic's own step size --
    # see its comment for why a fixed index offset cannot do this job. Kept
    # outside the ANGLE_DIRECTION product deliberately: direction is how the
    # index walks as rotation grows, the offset is a fixed rotation of the
    # whole set, and multiplying the two would silently flip the correction if
    # the direction were ever changed.
    # The offset applies ONLY when it lands on a whole stored step -- i.e. when
    # angle_count is a multiple of 8, since the offset is 45 degrees. That is
    # what the offset MEANS, not a special case for any one graphic: a
    # zero-point correction rotates which stored angle a rotation selects, so
    # if it does not map stored angles onto stored angles then the graphic's
    # angle set is not a 45-degree-compatible sampling of the circle, and there
    # is no sense in which it is "45 degrees out". It fires for every
    # angle_count that is not a multiple of 8, and 3, 6, 7, 9 and more are all
    # in real use.
    #
    # Walls are the case that motivated writing it down. They store 5 angles,
    # where 45 degrees is 0.625 of a step, so applying the offset re-quantized
    # every facing to a neighbour and moved walls a full 72-degree frame
    # (reported from a live window 2026-08-24, the same session the offset was
    # added for units). Walls no longer reach this function at all -- their
    # frames are shape variants rather than facings, so _rotation_is_variant()
    # diverts them to variant_index() -- but the skip above is general and
    # stays.
    offset_steps = ANGLE_ZERO_OFFSET_DEG / 360.0 * angle_count
    if offset_steps != int(offset_steps):
        offset_steps = 0.0
    # Rounds the SUM, not each term: the offset is exact only when angle_count
    # is a multiple of 8 (16 -> 2.0, 8 -> 1.0), and 25 -> 3.125 is a real case.
    # Rounding once is rounding the final angle, which is the quantity that has
    # to land on a stored frame.
    #
    # floor(x + 0.5), not round(): round() is banker's rounding, which breaks
    # exact .5 ties toward EVEN and so breaks them inconsistently. That only
    # became reachable once the offset could be fractional -- at angle_count 4
    # a 45-degree offset is exactly half a step, and banker's rounding then
    # sent rotations 0 and pi/2 to the same stored angle while pi and 3pi/2
    # went to different ones. Half-up is arbitrary too, but uniformly so, which
    # is what keeps distinct facings distinct.
    return math.floor(ANGLE_DIRECTION * steps + offset_steps + 0.5) % angle_count


