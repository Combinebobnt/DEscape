"""Which piece a cliff takes from its neighbours, measured from real scenario
placements, plus the tile-adjacency primitive the measurement is built from.

The pinned tables in `cliff_connectivity.json` are generated by
`tools/gen_cliff_connectivity.py` from a real scenario corpus -- see that
tool's module docstring for the adjacency definition and the family-pooling
justification.

**Piece size is the facing.** A piece's leg on an arm is tall (front, the
rock face toward the camera) when its footprint is 3 tiles across that arm,
else thin (back, the low ridge). Both ends of a join agree on that (98% of
the corpus's cardinal edge ends), and a run keeps its face on one side
through every corner (97% of two-arm corners). So a run has exactly two
dressings, face on one side or the other, and with the side known each
node's piece is a function of its typed arms: `resolve_shape()` is a lookup
over the generator's `shapes` rows, not a statistical choice. The Cliff
drag picks the side from its direction (`edge_tall()`, `DRAG_FACE_SIDE`),
`rewrite_frames()` gives an existing cliff its frame once it gains a
neighbour, and `offset()` says where each neighbour's footprint sits.

**`resolve()` and `rotations_for()` are the older per-shape majority table**
(`entries`): the commonest suffix for an exact 8-direction neighbour set, with
its top two rotations. It pools both facings, which is what its 61% purity
measures, so nothing is placed from it. It stays as a measurement.
"""

from __future__ import annotations

import json
from collections import defaultdict
from functools import lru_cache
from pathlib import Path

Direction = tuple[int, int]
Span = tuple[int, int]

_TABLE_PATH = Path(__file__).resolve().parent / "cliff_connectivity.json"


@lru_cache(maxsize=1)
def _data() -> dict:
    return json.loads(_TABLE_PATH.read_text())


def metadata() -> dict:
    """The generator's own coverage/purity report for the pinned table --
    see tools/gen_cliff_connectivity.py's docstring for what each field
    means and why the purity figures are lower than the plan first guessed."""
    return _data()["metadata"]


@lru_cache(maxsize=1)
def _table() -> dict[frozenset[Direction], tuple[int, tuple[int, ...]]]:
    table: dict[frozenset[Direction], tuple[int, tuple[int, ...]]] = {}
    for entry in _data()["entries"]:
        dirset = frozenset(tuple(d) for d in entry["dirset"])
        table[dirset] = (entry["suffix"], tuple(entry["rotations"]))
    return table


def resolve(dirset: frozenset[Direction]) -> tuple[int, tuple[int, ...]] | None:
    """(suffix, rotation candidates) for an exact neighbour-direction-set
    match, or None if this dirset wasn't common enough in the measured
    corpus to pin (see metadata()["min_n"]) -- a caller needs its own
    fallback for the unpinned ~5% of shapes, not provided here.

    The rotations here are the MAJORITY SUFFIX's. A caller that has a piece
    size of its own wants rotations_for() below instead; see its docstring
    for the measurement that makes the difference visible."""
    return _table().get(dirset)


@lru_cache(maxsize=1)
def _by_suffix() -> dict[tuple[frozenset[Direction], int], tuple[int, ...]]:
    table: dict[tuple[frozenset[Direction], int], tuple[int, ...]] = {}
    for entry in _data()["entries"]:
        dirset = frozenset(tuple(d) for d in entry["dirset"])
        for suffix, value in entry.get("rotations_by_suffix", {}).items():
            table[(dirset, int(suffix))] = tuple(value["rotations"])
    return table


def rotations_for(dirset: frozenset[Direction], suffix: int) -> tuple[int, ...] | None:
    """Rotation candidates measured for this neighbour shape AT THIS PIECE
    SIZE, or None if that pair was too rare to pin (metadata()["min_suffix_n"]).

    Rotation is strongly conditioned on suffix and the two must not be
    mixed: a {N, S} node at suffix 1 uses rotation 2 (192px of ink), the
    same dirset at suffix 2 uses 8/7 (90px) -- a 1x3 footprint holds thin
    shapes and a 3x3 holds big ones. Borrowing resolve()'s majority-suffix
    rotations for a different suffix draws a wrong-scale piece, which is
    exactly what made a straight run render as a thin line between tall end
    caps. A caller must fall back to its own manual value on None rather
    than to resolve(), or it reintroduces that bug silently."""
    return _by_suffix().get((dirset, suffix))


def _dirset_key(raw: list) -> frozenset[Direction]:
    return frozenset(tuple(d) for d in raw)


# Footprint per piece suffix, the same in every family but Short Marble Cliff 1
# (3x2). Leg types read this, never a const's real span, so pooling holds.
NOMINAL_SPAN: dict[int, Span] = {
    1: (3, 3), 2: (1, 3), 3: (3, 1), 4: (2, 3), 5: (2, 3), 6: (3, 2), 7: (3, 2), 8: (2, 2), 9: (2, 2)
}
# A (arms, suffix) row under this count is two separate runs abutting, not a shape.
SHAPE_FLOOR = 100
# Which side of a drag the face goes on, see edge_tall(). The game's own sense is unconfirmed.
DRAG_FACE_SIDE = 1
# No family has more than 24 frames (variant_index() wraps a stored 24).
_FRAME_COUNT = 24
# Frames 16..23 are the eight end caps: never right for a piece with two arms.
_FIRST_CAP_FRAME = 16


def leg_tall(suffix: int, d: Direction) -> bool:
    """Whether a piece's leg on its arm `d` is tall (front, the rock face) and
    not thin (back, the low ridge): its nominal footprint is 3 tiles across
    that arm."""
    span_x, span_y = NOMINAL_SPAN[suffix]
    return (span_y if d[0] else span_x) == 3


def edge_tall(step: Direction, side: int) -> bool:
    """Whether a run's edge travelled along `step` is tall. With `side == 1`
    the face is on the right of travel as seen on screen, so east and south
    are tall and west and north thin; `side == -1` flips it."""
    return (step[0] > 0 or step[1] > 0) == (side == 1)


class ShapeTables:
    """The parsed projections `resolve_shape()` and `offset()` read. `shapes`:
    per cardinal arm set, the pieces the corpus puts there and their frames,
    commonest first. `offsets` and `offsets_by_span`: where a neighbour's
    footprint sits. Built from the shipped JSON by default; a probe can build
    one from an in-memory document of the same shape (a held-out half)."""

    def __init__(self, data: dict) -> None:
        self.rows: dict[frozenset[Direction], list[tuple[int, int, tuple[int, ...]]]] = defaultdict(list)
        for row in sorted(data["shapes"], key=lambda r: r["suffix"]):
            frames = tuple(frame for frame, _ in row["frames"])
            self.rows[_dirset_key(row["arms"])].append((row["suffix"], row["n"], frames))
        self.twins = self._twins()
        self._cache: dict[tuple, tuple[int, tuple[int, ...]] | None] = {}
        self.offsets = {
            (_dirset_key(o["a"][0]), tuple(o["a"][1]), tuple(o["d"]), _dirset_key(o["b"][0]), tuple(o["b"][1])): tuple(
                o["offsets"][0][0]
            )
            for o in data.get("offsets", ())
        }
        self.offsets_by_span = {
            (tuple(o["a"]), tuple(o["d"]), tuple(o["b"])): tuple(o["offsets"][0][0])
            for o in data.get("offsets_by_span", ())
        }

    def _twins(self) -> dict[int, int]:
        """frame -> its art twin, read off the four straight rows' top two
        frames. Anything but 1/2, 4/5, 7/8 and 10/11 means the table is not
        the facing model's."""
        twins: dict[int, int] = {}
        for axis in (((0, -1), (0, 1)), ((-1, 0), (1, 0))):
            for tall in (True, False):
                row = self._best(dict.fromkeys(axis, tall), None)
                if row is None or len(row[2]) < 2:
                    raise ValueError(f"no straight row for arms {axis}, tall={tall}")
                a, b = row[2][:2]
                twins[a], twins[b] = b, a
        if sorted(twins.items()) != [(1, 2), (2, 1), (4, 5), (5, 4), (7, 8), (8, 7), (10, 11), (11, 10)]:
            raise ValueError(f"straight rows give twin frames {sorted(twins.items())}, not 1/2, 4/5, 7/8, 10/11")
        return twins

    def _best(self, arms: dict[Direction, bool], allowed) -> tuple[int, int, tuple[int, ...]] | None:
        """The commonest row at or over SHAPE_FLOOR whose legs have these
        types; a tie goes to the lower suffix (rows are in suffix order)."""
        best = None
        for row in self.rows.get(frozenset(arms), ()):
            suffix, n, _ = row
            if n < SHAPE_FLOOR or (allowed is not None and suffix not in allowed):
                continue
            if any(leg_tall(suffix, d) != tall for d, tall in arms.items()):
                continue
            if best is None or n > best[1]:
                best = row
        return best

    def _frames(self, frames: tuple[int, ...], arm_count: int, frame_limit: int) -> tuple[int, ...]:
        """The row's commonest frame plus its twin if it has one, less any the
        family lacks. A cap frame topping a row of two or more arms is two
        runs abutting, not a shape: nothing. Where the family lacks the
        commonest frame (Marble's 23 frames have no thin north cap 23), the
        row's next frame it has stands alone (user decision, 2026-10-19)."""
        limit = min(frame_limit, _FRAME_COUNT)
        # Only a real frame this family lacks: a row topped by the stored 24 still gives nothing.
        if limit <= frames[0] < _FRAME_COUNT and not (arm_count >= 2 and frames[0] >= _FIRST_CAP_FRAME):
            usable = [f for f in frames[1:] if f < limit and not (arm_count >= 2 and f >= _FIRST_CAP_FRAME)]
            return tuple(usable[:1])
        pair = (frames[0], self.twins.get(frames[0]))
        return tuple(
            sorted(f for f in pair if f is not None and f < limit and not (arm_count >= 2 and f >= _FIRST_CAP_FRAME))
        )

    def resolve(self, arms: dict[Direction, bool], *, allowed_suffixes, frame_limit: int):
        key = (tuple(sorted(arms.items())), frozenset(allowed_suffixes), frame_limit)
        if key not in self._cache:
            row = self._best(arms, key[1])
            frames = self._frames(row[2], len(arms), frame_limit) if row else ()
            self._cache[key] = (row[0], frames) if frames else None
        return self._cache[key]

    def rewrite(self, arms: frozenset[Direction], suffix: int, *, frame_limit: int) -> tuple[int, ...] | None:
        for row_suffix, n, frames in self.rows.get(arms, ()):
            if row_suffix == suffix and n >= SHAPE_FLOOR:
                return self._frames(frames, len(arms), frame_limit) or None
        return None


@lru_cache(maxsize=1)
def shape_tables() -> ShapeTables:
    return ShapeTables(_data())


def resolve_shape(
    arms: dict[Direction, bool],
    *,
    allowed_suffixes,
    frame_limit: int,
    tables: ShapeTables | None = None,
) -> tuple[int, tuple[int, ...]] | None:
    """(suffix, frames) of the piece for a node with these cardinal arms, each
    typed tall (True) or thin (False), or None when the corpus has no such
    piece. With a run's side known the piece is determined, so this is a
    lookup: the commonest row at or over SHAPE_FLOOR whose arm set matches and
    whose own legs have those types, among `allowed_suffixes`, a tie going to
    the lower suffix. Twin suffixes (s4/s5, s6/s7, s8/s9) so take the commoner.

    `frames` is the row's commonest frame, plus its art twin on a straight
    (1/2, 4/5, 7/8, 10/11; the caller alternates them by position), in
    ascending order. A frame at or past `frame_limit` (Marble has 23) or the
    stored 24 is left out, as is an end cap frame on two or more arms. Where
    that drops the commonest frame, the row's next usable frame is taken
    alone: Marble's thin north cap is 7, a thin straight."""
    return (tables or shape_tables()).resolve(arms, allowed_suffixes=allowed_suffixes, frame_limit=frame_limit)


def rewrite_frames(
    arms: frozenset[Direction],
    suffix: int,
    *,
    frame_limit: int,
    tables: ShapeTables | None = None,
) -> tuple[int, ...] | None:
    """`resolve_shape()`'s frames with the piece size fixed: what an existing
    cliff of this suffix shows once its cardinal neighbours are `arms`, or None
    when the corpus never gives that size those neighbours (the join would
    need a different-size piece)."""
    return (tables or shape_tables()).rewrite(frozenset(arms), suffix, frame_limit=frame_limit)


def offset(
    dirset_a: frozenset[Direction],
    span_a: Span,
    d: Direction,
    dirset_b: frozenset[Direction],
    span_b: Span,
    *,
    tables: ShapeTables | None = None,
) -> tuple[int, int] | None:
    """Modal offset of a `d`-neighbour's footprint low corner from this
    node's, for these dirsets and realized spans; else the span-only modal;
    else None (the caller centres nothing: cross-axis 0, resolved=False)."""
    t = tables or shape_tables()
    found = t.offsets.get((dirset_a, tuple(span_a), tuple(d), dirset_b, tuple(span_b)))
    if found is None:
        found = t.offsets_by_span.get((tuple(span_a), tuple(d), tuple(span_b)))
    return found


def adjacency_dir(a: tuple[int, int, int, int], b: tuple[int, int, int, int]) -> Direction | None:
    """8-direction tile-block adjacency between two `render.unit_tile_bounds()`
    boxes (half-open (x0, x1, y0, y1)), or None if they don't touch.
    Cardinal directions require a shared edge; diagonals require the boxes
    to meet at exactly one shared corner point. Tile-block, not
    centre-to-centre distance/angle, because cliff footprints range from
    1x3 to 3x3 -- see tools/gen_cliff_connectivity.py's module docstring."""
    ax0, ax1, ay0, ay1 = a
    bx0, bx1, by0, by1 = b
    x_overlap = ax0 < bx1 and bx0 < ax1
    y_overlap = ay0 < by1 and by0 < ay1
    if x_overlap and ay1 == by0:
        return (0, 1)
    if x_overlap and ay0 == by1:
        return (0, -1)
    if y_overlap and ax1 == bx0:
        return (1, 0)
    if y_overlap and ax0 == bx1:
        return (-1, 0)
    if ax1 == bx0 and ay1 == by0:
        return (1, 1)
    if ax1 == bx0 and ay0 == by1:
        return (1, -1)
    if ax0 == bx1 and ay1 == by0:
        return (-1, 1)
    if ax0 == bx1 and ay0 == by1:
        return (-1, -1)
    return None
